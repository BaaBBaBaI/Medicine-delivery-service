package ru.mirea.medicinedelivery.domain;

/**
 * Вычисляемый показатель приоритета и уровня фармацевтического контроля заказа.
 */
public enum DeliveryPriority {
    /** Приоритет не рассчитывается для уже доставленных или отменённых заказов. */
    NOT_APPLICABLE,
    /** Стандартная плановая доставка небольшого безрецептурного заказа. */
    LOW,
    /** Обычный приоритет для заказов средней стоимости без рецепта. */
    MEDIUM,
    /** Повышенный приоритет: рецептурный препарат либо крупная сумма заказа. */
    HIGH,
    /** Критический приоритет: рецептурный заказ высокой стоимости (строгий контроль). */
    CRITICAL
}
