package ru.mirea.medicinedelivery.domain;

/**
 * Три уровня прикладного доступа в системе доставки медикаментов:
 * <ul>
 *   <li>{@link #VIEWER} — просмотр заказов, справочника клиентов и аналитики (курьер / наблюдатель);</li>
 *   <li>{@link #PHARMACIST} — создание и редактирование заказов, заметок, массовых операций и CSV (фармацевт-диспетчер);</li>
 *   <li>{@link #ADMIN} — полное администрирование системы, справочника клиентов, пользователей и журнала аудита.</li>
 * </ul>
 */
public enum Role {
    VIEWER,
    PHARMACIST,
    ADMIN
}
